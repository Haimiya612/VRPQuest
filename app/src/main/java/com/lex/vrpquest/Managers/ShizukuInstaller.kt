package com.lex.vrpquest.Managers

import com.lex.vrpquest.Utils.ShizukuShell
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import java.io.File
import java.util.UUID

data class ShizukuInstallResult(
    val success: Boolean,
    val apkInstalled: Boolean,
    val obbInstalled: Boolean,
    val output: String
)

class ShizukuInstaller {

    companion object {
        private const val TEMP_DIRECTORY = "/data/local/tmp"
        private const val OBB_DIRECTORY = "/sdcard/Android/obb"
    }

    suspend fun installGame(
        packageName: String,
        apkFiles: List<File>,
        obbDirectory: File? = null
    ): ShizukuInstallResult = withContext(Dispatchers.IO) {

        require(
            packageName.matches(
                Regex("""[A-Za-z0-9_]+(\.[A-Za-z0-9_]+)+""")
            )
        ) {
            "Invalid Android package name."
        }

        check(ShizukuShell.isAvailable()) {
            "Start Shizuku and grant Rookie Quest permission first."
        }

        require(apkFiles.isNotEmpty()) {
            "No APK files provided."
        }

        apkFiles.forEach {
            require(it.isFile && it.canRead() &&
                it.extension.equals("apk", true)) {
                "Invalid or unreadable APK: ${it.name}"
            }
        }

        if (obbDirectory != null) {
            require(obbDirectory.isDirectory) {
                "OBB directory does not exist."
            }
        }

        val id = UUID.randomUUID().toString().replace("-", "")

        val tempFiles = apkFiles.indices.map {
            "$TEMP_DIRECTORY/vrp_${id}_$it.apk"
        }

        val commands = mutableListOf<String>()

        commands += "mkdir -p $TEMP_DIRECTORY"

        apkFiles.forEachIndexed { index, apk ->
            commands +=
                "cp -f -- ${quote(apk.canonicalPath)} " +
                "${quote(tempFiles[index])} || exit 21"
        }

        val installCommand = if (tempFiles.size == 1) {
            "pm install -r ${quote(tempFiles.first())}"
        } else {
            "pm install-multiple -r " +
                tempFiles.joinToString(" ") { quote(it) }
        }

        commands += "$installCommand || exit 22"
        commands += "echo VRP_APK_INSTALLED"

        if (obbDirectory != null) {
            val destination = "$OBB_DIRECTORY/$packageName"

            commands += "mkdir -p ${quote(destination)} || exit 31"
            commands +=
                "cp -R ${quote(obbDirectory.canonicalPath + "/.")} " +
                "${quote("$destination/")} || exit 32"

            commands += "echo VRP_OBB_INSTALLED"
        }

        // These filenames are generated by this app and contain
        // only safe characters.
        val cleanup = tempFiles.joinToString(" ")

        val script = buildString {
            appendLine("trap 'rm -f $cleanup' EXIT")
            commands.forEach { appendLine(it) }
            appendLine("echo VRP_INSTALL_COMPLETE")
        }

        val result = ShizukuShell.execute(script)

        val apkInstalled =
            result.output.contains("VRP_APK_INSTALLED")

        val obbInstalled =
            obbDirectory != null &&
                result.output.contains("VRP_OBB_INSTALLED")

        val successful =
            result.success &&
                apkInstalled &&
                (obbDirectory == null || obbInstalled)

        ShizukuInstallResult(
            success = successful,
            apkInstalled = apkInstalled,
            obbInstalled = obbInstalled,
            output = result.output
        )
    }

    private fun quote(value: String): String =
        "'" + value.replace("'", "'\\''") + "'"
}